import fs from 'node:fs';
import path from 'node:path';

const ROOT = fs.realpathSync(process.cwd());
const FEATURES_DIR = path.join(ROOT, 'src', 'features');
const OUT_FILE = path.join(ROOT, 'CODEMAP.md');

export function parseContractHeader(filePath) {
  const firstLine = fs.readFileSync(filePath, 'utf8').split(/\r?\n/)[0] || '';
  const match = firstLine.match(
    /^\/\/\s*@feature\s+(\S+)\s*\|\s*domain:\s*([^|]+)\|\s*slots:\s*([^|]+)\|\s*cmds:\s*([^|]+)\|\s*summary:\s*(.+)$/
  );
  if (!match) return null;
  return {
    name: match[1].trim(),
    domain: match[2].trim(),
    slots: match[3].trim(),
    cmds: match[4].trim(),
    summary: match[5].trim()
  };
}

export function buildCodemapText() {
  const rows = [];
  if (fs.existsSync(FEATURES_DIR)) {
    const dirs = fs.readdirSync(FEATURES_DIR, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
      .sort();
    for (const dir of dirs) {
      const contractPath = path.join(FEATURES_DIR, dir, `${dir}.contract.js`);
      if (!fs.existsSync(contractPath)) continue;
      const meta = parseContractHeader(contractPath);
      if (meta) {
        rows.push(`| \`${meta.name}\` | ${meta.domain} | ${meta.slots} | \`${meta.cmds}\` | ${meta.summary} |`);
      }
    }
  }

  const lines = [
    '# TasbihKu Feature Codemap',
    '',
    'Generated by `npm run codemap` from `src/features/*/*.contract.js` headers.',
    '',
    '| Feature | Domain | Slots | Commands | Summary |',
    '|---|---|---|---|---|',
    ...rows
  ];
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(import.meta.filename)) {
  fs.writeFileSync(OUT_FILE, buildCodemapText(), 'utf8');
  console.log(`CODEMAP.md updated (${buildCodemapText().split(/\r?\n/).length - 1} lines).`);
}
