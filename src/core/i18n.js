/**
 * Get translated string for key
 * @param {string} key 
 * @param {Object} [params] 
 * @returns {string}
 */
export function t(key, params = {}) {
    const lang = state.language || 'id';
    const dict = translations[lang] || translations.id;
    let str = dict[key] || translations.id[key] || key;

    if (params && typeof params === 'object') {
        for (const [paramKey, val] of Object.entries(params)) {
            str = str.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), val);
        }
    }
    return str;
}

/**
 * Set active application language
 * @param {'id'|'en'} lang 
 */
export function setLanguage(lang) {
    if (lang !== 'id' && lang !== 'en') return;
    updateState({ language: lang });
    saveState();
    applyTranslations();
    if (typeof document !== 'undefined') {
        document.documentElement.lang = lang;
    }
    if (typeof window !== 'undefined') {
        window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
    }
}

/**
 * Get current active language
 * @returns {'id'|'en'}
 */
export function getLanguage() {
    return state.language || 'id';
}

/**
 * Apply translations to DOM elements with data-i18n attributes
 */
export function applyTranslations() {
    if (typeof document === 'undefined') return;
    const lang = getLanguage();
    document.documentElement.lang = lang;

    // Standard text content replacement
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (key) {
            el.innerText = t(key);
        }
    });

    // HTML content replacement
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (key) {
            el.innerHTML = t(key);
        }
    });

    // Placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (key) {
            el.setAttribute('placeholder', t(key));
        }
    });

    // Aria labels
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria');
        if (key) {
            el.setAttribute('aria-label', t(key));
        }
    });

    // Title attributes
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (key) {
            el.setAttribute('title', t(key));
        }
    });

    // Synchronize selector if present
    const langSelect = document.getElementById('select-language');
    if (langSelect && langSelect.value !== lang) {
        langSelect.value = lang;
    }
}
